"""Time-based train / holdout split with a one-week gap.

  day          = TransactionDT // 86400
  cutoff_day   = 80th percentile of day
  train        = day <  cutoff_day - 7
  gap          = cutoff_day - 7 <= day < cutoff_day   (never used for training or scoring)
  holdout      = day >= cutoff_day

The gap keeps slow-arriving chargeback labels from leaking into training.
Writes the boundaries to data/clean/splits.json (read by every later stage)
and a summary to docs/splits.md.

Usage:
  python prep/split.py --parquet data/clean/train.parquet
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

DAY = 86_400
GAP_DAYS = 7


def compute_split(dt: pd.Series, gap_days: int = GAP_DAYS) -> dict:
    day = dt // DAY
    cutoff_day = int(np.percentile(day, 80))
    return {"cutoff_day": cutoff_day, "train_end_day": cutoff_day - gap_days, "gap_days": gap_days}


def assign(dt: pd.Series, split: dict) -> pd.Series:
    day = dt // DAY
    out = pd.Series("gap", index=dt.index)
    out[day < split["train_end_day"]] = "train"
    out[day >= split["cutoff_day"]] = "holdout"
    return out


def summarize(df: pd.DataFrame, part: pd.Series) -> pd.DataFrame:
    day = df["TransactionDT"] // DAY
    g = df.assign(part=part, day=day).groupby("part")
    return pd.DataFrame({
        "rows": g.size(),
        "fraud_rate": g["isFraud"].mean(),
        "first_day": g["day"].min(),
        "last_day": g["day"].max(),
        "fraud_amount": g.apply(lambda x: x.loc[x.isFraud == 1, "TransactionAmt"].sum(), include_groups=False),
    }).reindex(["train", "gap", "holdout"])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--parquet", default="data/clean/train.parquet")
    ap.add_argument("--out-json", default="data/clean/splits.json")
    ap.add_argument("--out-md", default="docs/splits.md")
    args = ap.parse_args()

    df = pd.read_parquet(args.parquet, columns=["TransactionID", "TransactionDT", "TransactionAmt", "isFraud"])
    split = compute_split(df["TransactionDT"])
    part = assign(df["TransactionDT"], split)
    s = summarize(df, part)
    src_file = Path(args.parquet).with_name("source.txt")
    split["source"] = src_file.read_text().strip() if src_file.exists() else args.parquet
    split["rows"] = {k: int(v) for k, v in s["rows"].items()}
    Path(args.out_json).write_text(json.dumps(split, indent=2))

    lines = [
        "# Time-based split",
        "",
        f"Generated by [`prep/split.py`](../prep/split.py) from `{split['source']}`"
        + (" (synthetic development sample, not results)." if "sample" in split["source"] else "."),
        "",
        f"cutoff_day = {split['cutoff_day']} (80th percentile of day); train is day < {split['train_end_day']}; "
        f"days {split['train_end_day']}–{split['cutoff_day'] - 1} are a {GAP_DAYS}-day gap; holdout is day >= {split['cutoff_day']}.",
        "",
        "| Part | Rows | Fraud rate | Days | Fraud $ |",
        "|---|---|---|---|---|",
    ]
    for name, r in s.iterrows():
        lines.append(f"| {name} | {int(r.rows):,} | {r.fraud_rate:.2%} | {int(r.first_day)}–{int(r.last_day)} | ${r.fraud_amount:,.0f} |")
    lines.append("")
    Path(args.out_md).write_text("\n".join(lines))
    print(s.to_string())


if __name__ == "__main__":
    main()
