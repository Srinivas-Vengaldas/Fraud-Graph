"""Profile the raw IEEE-CIS CSVs and write docs/data_profile.md.

Reports row counts, fraud rate, identity coverage, the TransactionDT range in
days, missing-value rates for the columns the project uses, and the top 10
DeviceInfo and P_emaildomain values.

Usage:
  python prep/profile_data.py --raw-dir data/raw --out docs/data_profile.md
"""

from __future__ import annotations

import argparse
from datetime import date
from pathlib import Path

import pandas as pd

DAY = 86_400

USED_TX_COLS = ["TransactionAmt", "ProductCD", "card1", "card2", "card3", "card4", "card5", "card6",
                "addr1", "addr2", "P_emaildomain", "R_emaildomain"] + [f"D{i}" for i in range(1, 16)]
USED_ID_COLS = ["DeviceType", "DeviceInfo", "id_30", "id_31", "id_33"]


def load_raw(raw_dir: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    # Only the columns the profile reports: the real file has 394 columns (~0.7 GB).
    header = pd.read_csv(raw_dir / "train_transaction.csv", nrows=0).columns
    keep = [c for c in ["TransactionID", "isFraud", "TransactionDT"] + USED_TX_COLS if c in header]
    tx = pd.read_csv(raw_dir / "train_transaction.csv", usecols=keep)
    tx.attrs["n_columns"] = len(header)
    ident = pd.read_csv(raw_dir / "train_identity.csv")
    return tx, ident


def profile(tx: pd.DataFrame, ident: pd.DataFrame) -> dict:
    days = tx["TransactionDT"] / DAY
    has_id = tx["TransactionID"].isin(ident["TransactionID"])
    merged = tx[["TransactionID"]].merge(ident, on="TransactionID", how="left")
    missing = {}
    for c in USED_TX_COLS:
        missing[c] = float(tx[c].isna().mean()) if c in tx else None
    for c in USED_ID_COLS:
        missing[c] = float(merged[c].isna().mean()) if c in merged else None
    return {
        "n_transactions": int(len(tx)),
        "n_tx_columns": int(tx.attrs.get("n_columns", tx.shape[1])),
        "n_identity": int(len(ident)),
        "n_id_columns": int(ident.shape[1]),
        "fraud_rate": float(tx["isFraud"].mean()),
        "n_fraud": int(tx["isFraud"].sum()),
        "identity_coverage": float(has_id.mean()),
        "fraud_rate_with_identity": float(tx.loc[has_id, "isFraud"].mean()) if has_id.any() else None,
        "fraud_rate_without_identity": float(tx.loc[~has_id, "isFraud"].mean()) if (~has_id).any() else None,
        "dt_min_days": float(days.min()),
        "dt_max_days": float(days.max()),
        "dt_span_days": float(days.max() - days.min()),
        "amount_median": float(tx["TransactionAmt"].median()),
        "fraud_amount_total": float(tx.loc[tx.isFraud == 1, "TransactionAmt"].sum()),
        "missing": missing,
        "top_device_info": ident["DeviceInfo"].value_counts().head(10).to_dict() if "DeviceInfo" in ident else {},
        "top_p_email": tx["P_emaildomain"].value_counts().head(10).to_dict(),
    }


def to_markdown(p: dict, source: str) -> str:
    def pct(x):
        return "n/a" if x is None else f"{x:.2%}"

    lines = [
        "# Data profile",
        "",
        f"Source: `{source}`. Generated by [`prep/profile_data.py`](../prep/profile_data.py) on {date.today().isoformat()}.",
        "",
        "| Fact | Value |",
        "|---|---|",
        f"| Transactions | {p['n_transactions']:,} ({p['n_tx_columns']} columns) |",
        f"| Fraud transactions | {p['n_fraud']:,} |",
        f"| Fraud rate | {pct(p['fraud_rate'])} |",
        f"| Identity rows | {p['n_identity']:,} ({p['n_id_columns']} columns) |",
        f"| Share of transactions with identity | {pct(p['identity_coverage'])} |",
        f"| Fraud rate with / without identity | {pct(p['fraud_rate_with_identity'])} / {pct(p['fraud_rate_without_identity'])} |",
        f"| TransactionDT range (days) | {p['dt_min_days']:.1f} to {p['dt_max_days']:.1f} (span {p['dt_span_days']:.1f}) |",
        f"| Median amount | ${p['amount_median']:,.2f} |",
        f"| Total fraud amount | ${p['fraud_amount_total']:,.0f} |",
        "",
        "## Missing-value rates (columns used)",
        "",
        "| Column | Missing |",
        "|---|---|",
    ]
    for c, v in p["missing"].items():
        lines.append(f"| {c} | {'column absent' if v is None else pct(v)} |")
    lines += ["", "## Top 10 DeviceInfo", "", "| DeviceInfo | Count |", "|---|---|"]
    lines += [f"| {k} | {v:,} |" for k, v in p["top_device_info"].items()]
    lines += ["", "## Top 10 P_emaildomain", "", "| P_emaildomain | Count |", "|---|---|"]
    lines += [f"| {k} | {v:,} |" for k, v in p["top_p_email"].items()]
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw-dir", default="data/raw")
    ap.add_argument("--out", default="docs/data_profile.md")
    args = ap.parse_args()
    raw = Path(args.raw_dir)
    tx, ident = load_raw(raw)
    p = profile(tx, ident)
    Path(args.out).write_text(to_markdown(p, str(raw)))
    print(f"fraud rate {p['fraud_rate']:.2%}, span {p['dt_span_days']:.1f} days, "
          f"identity coverage {p['identity_coverage']:.2%} -> {args.out}")


if __name__ == "__main__":
    main()
