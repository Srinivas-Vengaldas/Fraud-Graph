"""How well does each candidate key behave like "one customer"?

For card1 alone, card1|addr1, and the full card_entity (card1|addr1|birth day),
report the number of entities, transactions per entity, and label consistency:
among entities with 2+ transactions, the share whose labels all agree, and among
entities with any fraud, the share of their transactions that are fraud.
A key that really tracks one customer should have high consistency, because the
competition labels later transactions of a charged-back customer as fraud.

Also lists the device entities linked to the most card entities, which is the
supernode problem the ring builder has to cap.

Usage:
  python prep/entity_check.py --parquet data/clean/train.parquet --out docs/entities.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from entities import add_entity_columns, fmt


def key_stats(df: pd.DataFrame, key: pd.Series) -> dict:
    g = df.assign(k=key).groupby("k")["isFraud"]
    size = g.size()
    mean = g.mean()
    multi = size >= 2
    any_fraud = mean > 0
    return {
        "entities": int(len(size)),
        "tx_per_entity_mean": float(size.mean()),
        "tx_per_entity_p99": float(size.quantile(0.99)),
        "share_multi": float(multi.mean()),
        "label_consistent": float(((mean[multi] == 0) | (mean[multi] == 1)).mean()),
        "fraud_purity": float((g.sum()[any_fraud].sum()) / size[any_fraud].sum()),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--parquet", default="data/clean/train.parquet")
    ap.add_argument("--out", default="docs/entities.md")
    args = ap.parse_args()

    df = pd.read_parquet(args.parquet)
    df = add_entity_columns(df)
    src_file = Path(args.parquet).with_name("source.txt")
    source = src_file.read_text().strip() if src_file.exists() else args.parquet

    candidates = {
        "card1": df["card1"].map(fmt),
        "card1|addr1": df["card1"].map(fmt) + "|" + df["addr1"].map(fmt),
        "card_entity (card1|addr1|birth day)": df["card_entity"],
    }
    rows = {name: key_stats(df, k) for name, k in candidates.items()}

    dev = df[df["device_entity"].notna()]
    degree = dev.groupby("device_entity")["card_entity"].nunique().sort_values(ascending=False)

    lines = [
        "# Entity keys",
        "",
        f"Generated by [`prep/entity_check.py`](../prep/entity_check.py) from `{source}`"
        + (" (synthetic development sample, not results)." if "sample" in source else "."),
        "",
        "Label consistency: among entities with 2+ transactions, the share whose transactions all carry the same label. "
        "Fraud purity: among entities with any fraud, the share of their transactions labeled fraud.",
        "",
        "| Key | Entities | Tx per entity (mean / p99) | Entities with 2+ tx | Label consistency | Fraud purity |",
        "|---|---|---|---|---|---|",
    ]
    for name, s in rows.items():
        lines.append(f"| {name} | {s['entities']:,} | {s['tx_per_entity_mean']:.2f} / {s['tx_per_entity_p99']:.0f} | "
                     f"{s['share_multi']:.1%} | {s['label_consistent']:.1%} | {s['fraud_purity']:.1%} |")
    lines += [
        "",
        "## Device entities linked to the most card entities",
        "",
        f"{len(degree):,} device entities; {int((degree > 50).sum()):,} exceed a degree cap of 50.",
        "",
        "| Device entity | Distinct card entities |",
        "|---|---|",
    ]
    lines += [f"| `{k}` | {v:,} |" for k, v in degree.head(10).items()]
    lines.append("")
    Path(args.out).write_text("\n".join(lines))
    print("\n".join(lines[6:8 + len(rows)]))


if __name__ == "__main__":
    main()
