// Ring lift on the time holdout, with and without the supernode cap.
//
// Streams data/clean/events.jsonl (from prep/export_events.py) in time order through
// the same RingGraph the API uses. Training-period fraud marks its card and device
// entities as "prior fraud"; holdout labels are never fed back. For each holdout
// transaction we read its ring after adding its own link.
//
// Lift = fraud rate of holdout transactions in rings of size >= 3 with prior fraud
//        / overall holdout fraud rate.
//
// Usage: npx tsx scripts/ringEval.ts [--caps 50,20,10,5]   (always also runs with no cap)
import { createReadStream, readFileSync } from "node:fs";
import { createInterface } from "node:readline";
import { node, RingGraph } from "../src/graph/rings.js";
import { README, upsertResultsSection } from "./resultsMd.js";

interface Event {
  id: number;
  t: number;
  amt: number;
  y: number;
  part: "train" | "gap" | "holdout";
  card: string;
  device: string | null;
}

const capsArg = process.argv.indexOf("--caps");
const CAPS = (capsArg > 0 ? process.argv[capsArg + 1]! : "50,20,10,5").split(",").map(Number);
const EVENTS = new URL("../../data/clean/events.jsonl", import.meta.url).pathname;
const SOURCE = (() => {
  try {
    return readFileSync(new URL("../../data/clean/source.txt", import.meta.url), "utf8").trim();
  } catch {
    return "data/clean";
  }
})();

interface Tally {
  n: number;
  fraud: number;
  fraudAmt: number;
}
const tally = (): Tally => ({ n: 0, fraud: 0, fraudAmt: 0 });
const add = (t: Tally, e: Event) => {
  t.n++;
  t.fraud += e.y;
  t.fraudAmt += e.y ? e.amt : 0;
};

async function run(cap: number | null) {
  const g = new RingGraph({ degreeCap: cap });
  const all = tally();
  const risky = tally(); // ring size >= 3 and any prior fraud in the ring
  const riskyOthers = tally(); // ring size >= 3 and prior fraud on some OTHER entity
  const big = tally(); // ring size >= 3
  let largest = 0;
  const t0 = performance.now();
  const rl = createInterface({ input: createReadStream(EVENTS) });
  for await (const line of rl) {
    const e = JSON.parse(line) as Event;
    const r = g.addTransaction(e.card, e.device);
    if (e.part === "train" && e.y === 1) {
      g.markFraud(node("card", e.card));
      if (e.device !== null) g.markFraud(node("device", e.device));
    }
    if (e.part !== "holdout") continue;
    largest = Math.max(largest, r.ring_size);
    add(all, e);
    if (r.ring_size >= 3) {
      add(big, e);
      if (r.ring_fraud_entities > 0) add(risky, e);
      if (r.ring_fraud_others > 0) add(riskyOthers, e);
    }
  }
  return { cap, all, risky, riskyOthers, big, largest, supernodes: g.supernodeCount, rebuilds: g.rebuilds, ms: performance.now() - t0 };
}

const results = [await run(null)];
for (const c of CAPS) results.push(await run(c));
const pct = (x: number) => `${(100 * x).toFixed(2)}%`;
const rate = (t: Tally) => (t.n ? t.fraud / t.n : 0);
const lift = (t: Tally, base: Tally) => (rate(base) ? rate(t) / rate(base) : 0);

const lines = [
  "## Identity rings (holdout)",
  "",
  `Generated by [\`server/scripts/ringEval.ts\`](../server/scripts/ringEval.ts) from \`${SOURCE}\`` +
    (SOURCE.includes("sample") ? " (synthetic development sample, not results)." : "."),
  "Rings link card entities and device entities seen in the same transaction. Prior fraud comes from training-period labels only.",
  `Holdout: ${results[0]!.all.n.toLocaleString()} transactions, fraud rate ${pct(rate(results[0]!.all))}.`,
  "",
  "| Supernode cap | Supernodes cut | Largest ring | Flagged tx (size ≥3 + prior fraud) | Fraud rate when flagged | Lift | Fraud caught | Lift, prior fraud on another entity only |",
  "|---|---|---|---|---|---|---|---|",
];
for (const r of results) {
  lines.push(
    `| ${r.cap ?? "none"} | ${r.supernodes} | ${r.largest.toLocaleString()} | ${r.risky.n.toLocaleString()} (${pct(r.risky.n / r.all.n)}) | ` +
      `${pct(rate(r.risky))} | ${lift(r.risky, r.all).toFixed(1)}x | ${pct(r.all.fraud ? r.risky.fraud / r.all.fraud : 0)} | ` +
      `${lift(r.riskyOthers, r.all).toFixed(1)}x (${r.riskyOthers.n.toLocaleString()} tx) |`,
  );
}
lines.push(
  "",
  "Without the cap, generic device strings merge most device-bearing customers into one ring, so \"in a risky ring\" stops meaning anything. " +
    "The API uses a cap of 50 (DEGREE_CAP); smaller caps are shown to describe the trade-off and were not chosen on this holdout. " +
    "The last column excludes the transaction's own card entity, separating the ring signal from a plain blocklist hit.",
);
upsertResultsSection("rings", lines.join("\n"));
upsertResultsSection(
  "rings-summary",
  [
    `Holdout transactions in rings of 3+ entities that include prior fraud` +
      (SOURCE.includes("sample") ? " (synthetic development sample, not results)" : "") +
      `. From [\`server/scripts/ringEval.ts\`](server/scripts/ringEval.ts).`,
    "",
    "| Supernode cap | Largest ring | Flagged transactions | Fraud rate when flagged | Lift over baseline |",
    "|---|---|---|---|---|",
    ...results.map(
      (r) =>
        `| ${r.cap ?? "none"} | ${r.largest.toLocaleString()} | ${r.risky.n.toLocaleString()} | ${pct(rate(r.risky))} | ${lift(r.risky, r.all).toFixed(1)}x |`,
    ),
  ].join("\n"),
  README,
);
console.log(lines.join("\n"));
for (const r of results) console.log(`cap ${r.cap ?? "none"}: ${r.ms.toFixed(0)} ms, ${r.rebuilds} rebuilds`);
