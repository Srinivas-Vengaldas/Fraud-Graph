"""Score the API's stored decisions against the labels for one part of the split.

Joins the `decisions` table with isFraud from the Parquet file (labels never
went to the API) and reports recall, false-positive rate and dollars.
Writes a section of docs/results.md.

Usage:
  python ml/evaluate_decisions.py --part holdout --section baseline --title "Rules-only baseline"
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "prep"))
sys.path.insert(0, str(ROOT / "ml"))
from assumptions import COST_PER_REVIEW, MARGIN, net_dollars  # noqa: E402
from db import connect  # noqa: E402
from results_md import upsert_section  # noqa: E402
from split import assign  # noqa: E402


def metrics(df: pd.DataFrame) -> dict:
    fraud = df.isFraud == 1
    legit = ~fraud
    flagged = df.verdict != "approve"
    declined = df.verdict == "decline"
    reviewed = df.verdict == "review"
    amt = df.TransactionAmt
    return {
        "n": int(len(df)),
        "fraud_rate": float(fraud.mean()),
        "reviews": int(reviewed.sum()),
        "declines": int(declined.sum()),
        "recall": float((flagged & fraud).sum() / max(1, fraud.sum())),
        "recall_declined": float((declined & fraud).sum() / max(1, fraud.sum())),
        "fpr": float((flagged & legit).sum() / max(1, legit.sum())),
        "precision": float((flagged & fraud).sum() / max(1, flagged.sum())),
        "fraud_amt_total": float(amt[fraud].sum()),
        "fraud_amt_declined": float(amt[declined & fraud].sum()),
        "fraud_amt_reviewed": float(amt[reviewed & fraud].sum()),
        "legit_amt_declined": float(amt[declined & legit].sum()),
    }


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:
        return "unknown"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--parquet", default="data/clean/train.parquet")
    ap.add_argument("--splits", default="data/clean/splits.json")
    ap.add_argument("--part", default="holdout", choices=["train", "gap", "holdout"])
    ap.add_argument("--section", default="baseline")
    ap.add_argument("--title", default="Rules-only baseline")
    args = ap.parse_args()

    labels = pd.read_parquet(args.parquet, columns=["TransactionID", "TransactionDT", "TransactionAmt", "isFraud"])
    labels = labels[assign(labels.TransactionDT, json.loads(Path(args.splits).read_text())) == args.part]
    with connect() as conn:
        dec = pd.DataFrame(conn.execute("SELECT transaction_id, verdict, score, model_version FROM decisions").fetchall(),
                           columns=["TransactionID", "verdict", "score", "model_version"])
    df = labels.merge(dec, on="TransactionID", how="inner")
    missing = len(labels) - len(df)
    m = metrics(df)
    net = net_dollars(m["fraud_amt_declined"], m["fraud_amt_reviewed"], m["reviews"], m["legit_amt_declined"])
    source = (ROOT / "data/clean/source.txt").read_text().strip() if (ROOT / "data/clean/source.txt").exists() else "?"

    body = "\n".join([
        f"## {args.title} ({args.part})",
        "",
        f"Generated by [`ml/evaluate_decisions.py`](../ml/evaluate_decisions.py) at commit `{git_commit()}` from API decisions "
        f"on `{source}`" + (" (synthetic development sample, not results)." if "sample" in source else "."),
        f"Decisions found for {len(df):,} of {len(labels):,} {args.part} transactions"
        + (f" ({missing:,} not replayed)." if missing else "."),
        f"Assumptions: ${COST_PER_REVIEW:.0f} per review, {MARGIN:.0%} margin lost on a declined good transaction, a reviewed fraud is stopped.",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Fraud rate | {m['fraud_rate']:.2%} |",
        f"| Reviews / declines | {m['reviews']:,} / {m['declines']:,} |",
        f"| Recall (review or decline) | {m['recall']:.2%} |",
        f"| Recall (decline only) | {m['recall_declined']:.2%} |",
        f"| False-positive rate | {m['fpr']:.2%} |",
        f"| Precision of flagged | {m['precision']:.2%} |",
        f"| Fraud $ declined / reviewed / total | ${m['fraud_amt_declined']:,.0f} / ${m['fraud_amt_reviewed']:,.0f} / ${m['fraud_amt_total']:,.0f} |",
        f"| Good-customer $ declined | ${m['legit_amt_declined']:,.0f} |",
        f"| Net dollars saved | ${net:,.0f} |",
    ])
    upsert_section(args.section, body)
    print(body)
    out = ROOT / "data/clean" / f"eval_{args.section}.json"
    out.write_text(json.dumps({**m, "net": net, "commit": git_commit()}, indent=2))


if __name__ == "__main__":
    main()
