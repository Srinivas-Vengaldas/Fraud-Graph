"""Report the model once on the time holdout: PR-AUC, recall at 1% FPR, precision of the top-k review queue.

Scores come from the saved model on the holdout's logged features. Results are
saved with the git commit hash to ml/artifacts/eval.json and docs/results.md.

Usage:
  python ml/evaluate.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import lightgbm as lgb

from dataset import ARTIFACTS, ROOT, encode, load_table, save_json
from metrics import summary
from results_md import upsert_section

sys.path.insert(0, str(ROOT / "prep"))


def git_commit() -> str:
    try:
        dirty = subprocess.run(["git", "diff", "--quiet"], cwd=ROOT).returncode != 0
        h = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
        return h + ("-dirty" if dirty else "")
    except Exception:
        return "unknown"


def main() -> None:
    spec = json.loads((ARTIFACTS / "feature_spec.json").read_text())
    meta = json.loads((ARTIFACTS / "train_meta.json").read_text())
    model = lgb.Booster(model_file=str(ARTIFACTS / "model.txt"))
    df = load_table()
    ho = df[df.part == "holdout"]
    s = model.predict(encode(ho, spec))
    y = ho.isFraud.to_numpy()
    k = max(1, int(0.01 * len(ho)))
    res = {"commit": git_commit(), "model_trained_at_commit": meta["commit"], "holdout": summary(y, s, k),
           "validation": meta["validation"]}
    save_json("eval.json", res)
    source = (ROOT / "data/clean/source.txt").read_text().strip()
    h, v = res["holdout"], res["validation"]
    body = "\n".join([
        "## Model (LightGBM) on the time holdout",
        "",
        f"Generated by [`ml/evaluate.py`](../ml/evaluate.py) at commit `{res['commit']}` (model from [`ml/train.py`](../ml/train.py) "
        f"at `{meta['commit']}`) on `{source}`" + (" (synthetic development sample, not results)." if "sample" in source else "."),
        f"Trained on days {meta['train_days'][0]}–{meta['train_days'][1]}, early-stopped on days "
        f"{meta['valid_days'][0]}–{meta['valid_days'][1]}; holdout untouched until this run.",
        "",
        "| Metric | Validation | Holdout |",
        "|---|---|---|",
        f"| Rows / fraud rate | {v['n']:,} / {v['fraud_rate']:.2%} | {h['n']:,} / {h['fraud_rate']:.2%} |",
        f"| PR-AUC | {v['pr_auc']:.4f} | {h['pr_auc']:.4f} |",
        f"| ROC-AUC | {v['roc_auc']:.4f} | {h['roc_auc']:.4f} |",
        f"| Recall at 1% FPR | {v['recall_at_1pct_fpr']:.2%} | {h['recall_at_1pct_fpr']:.2%} |",
        f"| Precision of top 1% (k={h['top_k']}) | {v['precision_at_top_k']:.2%} | {h['precision_at_top_k']:.2%} |",
        "",
        "Accuracy is not reported: approving everything is already about 97% accurate.",
    ])
    upsert_section("model", body)
    print(body)


if __name__ == "__main__":
    main()
